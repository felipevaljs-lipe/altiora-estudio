import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    expect(fixture.componentInstance).toBeTruthy();
  });

  it('should render the landing page sections', async () => {
    const fixture = TestBed.createComponent(App);
    fixture.detectChanges();
    await fixture.whenStable();
    const compiled = fixture.nativeElement as HTMLElement;

    expect(compiled.querySelector('en-header')).toBeTruthy();
    expect(compiled.querySelector('#servicios')).toBeTruthy();
    expect(compiled.querySelector('#contacto')).toBeTruthy();
    expect(compiled.querySelector('en-footer')).toBeTruthy();
  });
});
